import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const read=path=>readFile(new URL(path,root),'utf8');
const plain=source=>source.replace(/^import .*?;\n/gm,'').replace(/^export \{[^}]+\};?\s*$/gm,'').replace(/^export /gm,'');
const parser='// Generated by npm run build:standalone; edit src modules instead.\n'+[await read('src/model-schema.js'),await read('src/parsers.js'),await read('src/memory.js')].map(plain).join('\n');
const inline=source=>source.replace(/<\/script/gi,'<\\/script');
const styles=await read('standalone/styles.css');
const app=await read('standalone/app.js');
const html=(await read('standalone/index.html'))
 .replace('<link rel="stylesheet" href="styles.css"/>',()=>`<style>\n${styles}\n</style>`)
 .replace('<script src="parser.js"></script><script src="app.js"></script>',()=>`<script>\n${inline(parser)}\n</script><script>\n${inline(app)}\n</script>`);

for(const [path,content] of [['standalone/parser.js',parser],['llm-anatomy-demo.html',html]]) {
 if(process.argv.includes('--check')) {
  if(await read(path)!==content) throw new Error(`${path} устарел; выполните npm run build:standalone`);
 } else await writeFile(new URL(path,root),content);
}
console.log(process.argv.includes('--check')?'Standalone artifacts are up to date':'Standalone artifacts generated');
